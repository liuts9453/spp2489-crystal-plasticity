#!/usr/bin/env python3
"""Generate non-destructive per-grain MOOSE material blocks for the FCC CP benchmark."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
GRAIN_DATA = ROOT / "results/polycrystal/grain_data.csv"
DEFAULT_OUTPUT = ROOT / "examples/crystal_plasticity/cp_20_random_materials.i"
CUBIC_C = "200000 120000 120000 200000 120000 200000 100000 100000 100000"


def load_orientations(mode: str) -> list[tuple[float, float, float]]:
    with GRAIN_DATA.open(newline="", encoding="utf-8") as stream:
        rows = list(csv.DictReader(stream))
    if len(rows) != 20:
        raise RuntimeError(f"Expected 20 grains in {GRAIN_DATA}, found {len(rows)}")
    if mode == "same":
        return [(37.0, 52.0, 11.0)] * 20
    return [
        (float(row["phi1_deg"]), float(row["Phi_deg"]), float(row["phi2_deg"]))
        for row in rows
    ]


def generate(orientations: list[tuple[float, float, float]], output: Path) -> None:
    phi1 = " ".join(f"{angles[0]:.12g}" for angles in orientations)
    Phi = " ".join(f"{angles[1]:.12g}" for angles in orientations)
    phi2 = " ".join(f"{angles[2]:.12g}" for angles in orientations)
    lines = [
        "# Generated by scripts/crystal_plasticity/generate_cp_materials.py; do not edit in place.",
        f"orientation_phi1 = '{phi1}'",
        f"orientation_Phi = '{Phi}'",
        f"orientation_phi2 = '{phi2}'",
        "",
        "[Materials]",
    ]
    for grain, (a1, a2, a3) in enumerate(orientations, start=1):
        tag = f"g{grain:02d}"
        lines.extend(
            [
                f"  [elasticity_{tag}]",
                "    type = ComputeElasticityTensorCP",
                f"    block = {grain}",
                "    fill_method = symmetric9",
                f"    C_ijkl = '{CUBIC_C}'",
                f"    euler_angle_1 = {a1:.15g}",
                f"    euler_angle_2 = {a2:.15g}",
                f"    euler_angle_3 = {a3:.15g}",
                "  []",
                f"  [analytic_cp_{tag}]",
                "    type = ComputeLagrangianFCCCrystalPlasticityStress",
                f"    block = {grain}",
                "    slip_system_file = fcc_12_slip_systems.txt",
                "    reference_slip_rate = 0.001",
                "    rate_sensitivity = ${cp_xm}",
                "    initial_slip_resistance = 80",
                "    hardening_modulus = 400",
                "    saturation_resistance = 160",
                "    hardening_exponent = 1.0",
                "    latent_hardening_ratio = 1.4",
                "    slip_increment_tolerance = 0.02",
                "    local_absolute_tolerance = 1e-10",
                "    local_relative_tolerance = 1e-9",
                "    local_max_iterations = 60",
                "    local_solver_mode = ${cp_local_solver}",
                "    reuse_tangent_factorization = ${cp_reuse_lu}",
                "    optimized_tensor_evaluation = ${cp_optimize_tensors}",
                "    specialize_scalar_operations = ${cp_optimize_scalars}",
                "    local_predictor = ${cp_predictor}",
                "  []",
                f"  [diagnostics_{tag}]",
                "    type = CrystalPlasticityDiagnostics",
                f"    block = {grain}",
                "  []",
            ]
        )
    lines.extend(["[]", "", "[Postprocessors]"])
    for grain in range(1, 21):
        lines.extend(
            [
                f"  [grain_{grain:02d}_slip]",
                "    type = ElementAverageMaterialProperty",
                "    mat_prop = accumulated_slip",
                f"    block = {grain}",
                "    execute_on = TIMESTEP_END",
                "  []",
            ]
        )
    lines.extend(["[]", ""])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=("random", "same"), default="random")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    generate(load_orientations(args.mode), args.output.resolve())
    print(args.output.resolve())


if __name__ == "__main__":
    main()
