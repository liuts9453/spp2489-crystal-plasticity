#!/usr/bin/env python3
"""Generate the fixed-seed Voronoi centers and Haar-uniform crystal orientations."""

from __future__ import annotations

import csv
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
EXAMPLES = ROOT / "examples"
RESULTS = ROOT / "results" / "polycrystal"
SEED = 2026
GRAIN_COUNT = 20
CELL_SIZE = 200.0
CUBIC_VALUES = "200000 120000 120000 200000 120000 200000 100000 100000 100000"


def format_values(values: np.ndarray) -> str:
    return " ".join(f"{value:.12g}" for value in values.ravel())


def main() -> None:
    rng = np.random.default_rng(SEED)
    centers = rng.uniform(0.0, CELL_SIZE, size=(GRAIN_COUNT, 2))

    # phi1 and phi2 are uniform; cos(Phi) is uniform for Haar measure on SO(3).
    phi1 = rng.uniform(0.0, 360.0, size=GRAIN_COUNT)
    Phi = np.degrees(np.arccos(rng.uniform(-1.0, 1.0, size=GRAIN_COUNT)))
    phi2 = rng.uniform(0.0, 360.0, size=GRAIN_COUNT)

    center_text = (
        f"# Generated by scripts/generate_polycrystal_data.py with NumPy seed {SEED}.\n"
        f"voronoi_centers = '{format_values(centers)}'\n"
    )
    (EXAMPLES / "polycrystal_20_centers.i").write_text(center_text, encoding="utf-8")

    lines = [
        f"# Generated by scripts/generate_polycrystal_data.py with NumPy seed {SEED}.",
        f"orientation_phi1 = '{format_values(phi1)}'",
        f"orientation_Phi = '{format_values(Phi)}'",
        f"orientation_phi2 = '{format_values(phi2)}'",
        "",
        "[Materials]",
    ]
    for grain, angles in enumerate(zip(phi1, Phi, phi2), start=1):
        lines.extend(
            [
                f"  [elasticity_g{grain:02d}]",
                "    type = ComputeElasticityTensor",
                f"    block = {grain}",
                "    fill_method = symmetric9",
                f"    C_ijkl = '{CUBIC_VALUES}'",
                f"    euler_angle_1 = {angles[0]:.12g}",
                f"    euler_angle_2 = {angles[1]:.12g}",
                f"    euler_angle_3 = {angles[2]:.12g}",
                "  []",
                f"  [stress_g{grain:02d}]",
                "    type = ComputeCubicHyperelasticStress",
                f"    block = {grain}",
                "  []",
            ]
        )
    lines.append("[]")
    (EXAMPLES / "polycrystal_20_random_materials.i").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )

    RESULTS.mkdir(parents=True, exist_ok=True)
    with (RESULTS / "grain_data.csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.writer(stream)
        writer.writerow(["grain_id", "seed_x_um", "seed_y_um", "phi1_deg", "Phi_deg", "phi2_deg"])
        for grain in range(GRAIN_COUNT):
            writer.writerow(
                [
                    grain + 1,
                    centers[grain, 0],
                    centers[grain, 1],
                    phi1[grain],
                    Phi[grain],
                    phi2[grain],
                ]
            )
    print(f"Wrote fixed-seed data for {GRAIN_COUNT} grains")


if __name__ == "__main__":
    main()
